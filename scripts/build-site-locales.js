'use strict';
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '../public/i18n');
const catalogs = Object.fromEntries(['es', 'pt-BR', 'fr', 'de'].map(code =>
  [code, JSON.parse(fs.readFileSync(path.join(dir, code + '.json'), 'utf8'))]));
const keys = Object.keys(catalogs.es).sort();
const slots = text => JSON.stringify((text.match(/\{\d+\}/g) || []).sort());
for (const [code, catalog] of Object.entries(catalogs)) {
  if (JSON.stringify(Object.keys(catalog).sort()) !== JSON.stringify(keys)) throw Error('Missing keys: ' + code);
  for (const [source, value] of Object.entries(catalog)) {
    if (typeof value !== 'string' || !value.trim()) throw Error('Empty translation: ' + code + ': ' + source);
    if (slots(source) !== slots(value)) throw Error('Changed placeholders: ' + code + ': ' + source);
  }
}
const output = '/* Generated by scripts/build-site-locales.js. Edit the JSON catalogs. */\n' +
  '(function(root) { root.KaiLocaleCatalogs = ' + JSON.stringify(catalogs) +
  '; })(typeof window === "object" ? window : globalThis);\n';
const file = path.join(dir, 'catalogs.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== output) throw Error('Run node scripts/build-site-locales.js');
} else fs.writeFileSync(file, output);
console.log('Website: English + 4 translations; ' + keys.length + ' messages per language.');
